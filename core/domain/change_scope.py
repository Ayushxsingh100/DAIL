"""The allowed change scope of a generated candidate, and the operation check (Doc 10 §14-§15;
C-190, C-191).

§15: "AllowedChangeScope { resource_addresses[], resource_types[], attributes[],
operation_types = CREATE | MODIFY | DELETE | REPLACE }. The scope is generated by the
experiment/controller, not chosen by the LLM." It lives in ``core.domain`` because the
controller (``core.application``, later the experiment harness) builds it and ``core`` may not
import ``llm`` (R3).

``operation_breaches(report, scope)`` is the check of C-191: after DAIL's own identity engine has
compared the candidate with its parent, every change must be an allowed operation: CREATED is
CREATE, MODIFIED is MODIFY, DELETED is DELETE, REPLACED is REPLACE, and an UNCERTAIN match counts as
REPLACE (the cautious reading: identity could not exclude a replacement). Doc 10 §14 "Destructive
operations outside the defined experiment scope are rejected" is enforced on DAIL's identity, never
on the model's claim.

Standard library and ``core.domain`` only (R1).
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from dataclasses import dataclass
from enum import StrEnum
from typing import Final

from core.domain.enums import ChangeType
from core.domain.errors import DomainValidationError
from core.domain.identity import IdentityReport


class OperationType(StrEnum):
    """§15 ``operation_types``."""

    CREATE = "CREATE"
    MODIFY = "MODIFY"
    DELETE = "DELETE"
    REPLACE = "REPLACE"


ALL_OPERATIONS: Final = (
    OperationType.CREATE,
    OperationType.MODIFY,
    OperationType.DELETE,
    OperationType.REPLACE,
)
OPERATION_OF_CHANGE: Final = {
    ChangeType.CREATED: OperationType.CREATE,
    ChangeType.MODIFIED: OperationType.MODIFY,
    ChangeType.DELETED: OperationType.DELETE,
    ChangeType.REPLACED: OperationType.REPLACE,
    ChangeType.UNCERTAIN: OperationType.REPLACE,
}
_NAME = r"[A-Za-z_][A-Za-z0-9_-]*"
CONFIG_ADDRESS: Final = re.compile(rf"^({_NAME})\.({_NAME})$")


def _texts(values: Iterable[object], field: str) -> tuple[str, ...]:
    if isinstance(values, str):
        raise DomainValidationError(f"AllowedChangeScope.{field}: must be a list, not a string")
    items: list[str] = []
    for item in values:
        if not isinstance(item, str) or item == "":
            raise DomainValidationError(f"AllowedChangeScope.{field}: must hold non-empty strings")
        items.append(item)
    return tuple(sorted(set(items)))


@dataclass(frozen=True)
class AllowedChangeScope:
    """§15. Addresses are configuration addresses (``type.name``, C-189)."""

    resource_addresses: tuple[str, ...]
    resource_types: tuple[str, ...]
    attributes: tuple[str, ...]
    operation_types: tuple[OperationType, ...]

    def __post_init__(self) -> None:
        addresses = _texts(self.resource_addresses, "resource_addresses")
        for address in addresses:
            if CONFIG_ADDRESS.match(address) is None:
                raise DomainValidationError(
                    f"AllowedChangeScope.resource_addresses: {address!r} is not type.name (C-189)"
                )
        object.__setattr__(self, "resource_addresses", addresses)
        object.__setattr__(self, "resource_types", _texts(self.resource_types, "resource_types"))
        object.__setattr__(self, "attributes", _texts(self.attributes, "attributes"))
        operations = []
        for item in self.operation_types:
            try:
                operations.append(OperationType(item))
            except ValueError as error:
                raise DomainValidationError(
                    f"AllowedChangeScope.operation_types: unknown operation {item!r}"
                ) from error
        order = {op: i for i, op in enumerate(ALL_OPERATIONS)}
        object.__setattr__(
            self, "operation_types", tuple(sorted(set(operations), key=order.__getitem__))
        )

    def to_dict(self) -> dict[str, list[str]]:
        return {
            "resource_addresses": list(self.resource_addresses),
            "resource_types": list(self.resource_types),
            "attributes": list(self.attributes),
            "operation_types": [op.value for op in self.operation_types],
        }


def operation_breaches(report: IdentityReport, scope: AllowedChangeScope) -> tuple[str, ...]:
    """The changes of ``report`` whose operation ``scope`` does not allow (C-191), sorted."""
    found = []
    for match in report.resource_matches:
        operation = OPERATION_OF_CHANGE.get(match.change_type)
        if operation is None or operation in scope.operation_types:
            continue
        found.append(
            f"{match.key}: {match.change_type.value} is {operation.value}, which the scope "
            "does not allow (C-191)"
        )
    return tuple(sorted(found))
