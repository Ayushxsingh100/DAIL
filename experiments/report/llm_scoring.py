"""``docs/P10C_LLM_PILOT_SCORING.md``: the dev LLM pilots scored against TP-L1 (P10c Section 3.4;
C-228).

``render`` writes the Markdown of the JSON that ``experiments.scoring.llm_pilot.score`` returns; the
JSON is the record and the Markdown its rendering (a test renders the committed JSON and compares).
Descriptive only: the LLM track carries no hypothesis (C-228).
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

CONDITIONS = ("A", "B", "C", "C_PRIME")
CELLS = (
    "promoted safe",
    "promoted unsafe",
    "promoted no label",
    "rejected safe",
    "rejected unsafe",
    "rejected no label",
)


def _table(head: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + [
        "| " + " | ".join(r) + " |" for r in rows
    ]


def _rate(r: Mapping[str, Any]) -> str:
    return f"{r['numerator']} / {r['denominator']}"


def render(report: Mapping[str, Any]) -> str:
    gens = {g["generation_id"]: g for g in report["generations"]}
    name = {gid: f"{g['name']} ({g['prompt_version']})" for gid, g in gens.items()}
    lines = [
        "# P10c: the dev LLM pilots scored against TerraPreserve's TP-L1 labels",
        "",
        "Generated by `python -m experiments.report llm-scoring` from DAIL's frozen records and",
        "TP-L1's label files; do not edit by hand. Dev split only. Descriptive only: no hypothesis",
        "rests on LLM candidates (C-228).",
        "",
        f"- TerraPreserve labels: commit `{report['tp_commit']}` (TP-L1, C-230); each "
        "`labels.json` checked against its `labels.sha256`, each label's export, content and tree",
        "  hashes against DAIL's export",
        f"- Validate gate: `{report['gate_name']}` (C-227); replay: `{report['replay_name']}`",
        "",
    ]
    for g in report["generations"]:
        lines.append(
            f"- `{g['generation_id']}` {name[g['generation_id']]}: export sha256 "
            f"`{g['export_sha256']}`, {g['label_count']} labelled candidates"
        )
    lines += ["", "## 1. Valid patches before and after the `terraform validate` gate", ""]
    rows = []
    for g in report["generations"]:
        for model, r in g["gate_rates"].items():
            rows.append(
                [
                    name[g["generation_id"]],
                    model,
                    str(r["attempts"]),
                    _rate(r["before"]),
                    _rate(r["after"]),
                ]
            )
    lines += _table(
        ["Generation", "Model", "Attempts", "Valid before the gate", "Valid after"], rows
    )
    lines += [
        "",
        "Before: the patch passed validators 1 or 2 (P10a, P10b). After: its rebuilt candidate",
        "also passes the pinned `terraform validate` (Terraform 1.15.8, `hashicorp/aws` 6.53.0).",
        "",
        "## 2. Label classes",
        "",
    ]
    rows = []
    for m in report["models"]:
        classes = m["classes"]
        no = (
            ", ".join(
                f"{k.removeprefix('no label: ')} {v}"
                for k, v in sorted(classes.items())
                if k.startswith("no label")
            )
            or "0"
        )
        rows.append(
            [
                name[m["generation_id"]],
                m["model"],
                str(m["attempts"]),
                str(m["valid_before_gate"]),
                str(m["validate_valid"]),
                str(classes.get("safe", 0)),
                str(classes.get("unsafe", 0)),
                no,
            ]
        )
    lines += _table(
        [
            "Generation",
            "Model",
            "Attempts",
            "Valid before gate",
            "Validate-valid",
            "Safe",
            "Unsafe",
            "No label (reason)",
        ],
        rows,
    )
    lines += ["", "Classes are given for every patch that was valid before the gate.", ""]
    for scope, title in (
        ("validate_valid", "the validate-valid candidates"),
        ("all_replayed", "every replayed candidate (before the gate)"),
    ):
        lines += [f"## {3 if scope == 'validate_valid' else 4}. Decisions by class: {title}", ""]
        rows = []
        for m in report["models"]:
            for c in CONDITIONS:
                cell = m["conditions"][scope][c]
                rows.append(
                    [name[m["generation_id"]], m["model"], c, *[str(cell[k]) for k in CELLS]]
                )
        lines += _table(
            ["Generation", "Model", "Condition", *[c.capitalize() for c in CELLS]], rows
        )
        lines.append("")
    lines += ["## 5. A's promotions of unsafe candidates", ""]
    found = report["a_unsafe_promotions"]
    if found:
        lines += _table(
            ["Generation", "Candidate", "FAIL", "Validate-valid"],
            [
                [
                    name[a["generation_id"]],
                    f"{a['model']}/{a['scenario_id']}/{a['k']}",
                    ", ".join(a["fail"]),
                    str(a["validate_ok"]),
                ]
                for a in found
            ],
        )
    else:
        lines.append("None.")
    agreement = report["validate_agreement"]
    lines += [
        "",
        "## 6. DAIL's validate gate against TP-L1's `terraform validate`",
        "",
        f"Compared: {agreement['compared']}; agree: {agreement['agree']}; disagree: "
        f"{len(agreement['disagreements'])}; not comparable (TP-L1 gave no plan): "
        f"{len(agreement['not_comparable'])}. Every disagreement is listed; none is resolved.",
        "",
    ]
    rows = [
        [
            name[a["generation_id"]],
            f"{a['model']}/{a['scenario_id']}/{a['k']}",
            str(a["dail_validate_ok"]),
            str(a["tp_l1_validate_ok"]),
            (a["dail_error"] or "").replace("|", "/")[:160],
            (a["tp_l1_error"] or "").replace("|", "/")[:160],
        ]
        for a in agreement["disagreements"] + agreement["not_comparable"]
    ]
    if rows:
        lines += _table(
            ["Generation", "Candidate", "DAIL valid", "TP-L1 valid", "DAIL error", "TP-L1 error"],
            rows,
        )
    else:
        lines.append("No disagreement.")
    lines.append("")
    return "\n".join(lines)
