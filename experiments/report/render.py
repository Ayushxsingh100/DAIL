"""The Markdown rendering of an ExperimentReport (P8b Step 5; Doc 13 §35).

Every number comes from the report document. A proportion is shown as ``k / n = p [low, high]``
(Wilson 95%); a count or an amount as it is. The rendering is deterministic: the same report gives
the same text, and ``tests/unit/test_p8b_scoring_report.py`` checks that ``docs/P8_DEV_PILOT.md`` is
the rendering of ``docs/P8_DEV_PILOT.json``. Descriptive only (C-214).
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from typing import Any

NAMES = {"A": "A", "B": "B", "C": "C", "C_PRIME": "C′"}


class _Index:
    def __init__(self, report: Mapping[str, Any]) -> None:
        self.by_key: dict[tuple[str, str, str, str], Mapping[str, Any]] = {}
        for m in [*report["primary_metrics"], *report["secondary_metrics"]]:
            self.by_key[(m["metric_name"], m["condition_id"], m["scope"], m["stratum"])] = m

    def get(
        self, name: str, condition: str, scope: str = "all", stratum: str = "all"
    ) -> Mapping[str, Any] | None:
        return self.by_key.get((name, condition, scope, stratum))

    def strata(self, prefix: str) -> list[str]:
        return sorted({k[3] for k in self.by_key if k[3].startswith(prefix)})


def _num(value: Any) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        if value.is_integer():
            return str(int(value))
        return f"{value:.3f}"
    return str(value)


def cell(m: Mapping[str, Any] | None) -> str:
    if m is None:
        return "—"
    if m["unit"] == "proportion":
        low, high = m["wilson95"] or (None, None)
        interval = "" if low is None else f" [{low:.3f}, {high:.3f}]"
        value = "n/a" if m["value"] is None else f"{m['value']:.3f}"
        return f"{m['numerator']} / {m['denominator']} = {value}{interval}"
    if m["unit"] == "saving":
        value = "n/a" if m["value"] is None else f"{m['value']:.3f}"
        return f"1 − {m['numerator']} / {m['denominator']} = {value}"
    return _num(m["value"])


def _table(head: Sequence[str], rows: Iterable[Sequence[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


HEADLINE = (
    ("Unsafe promoted / promoted", "unsafe_promotions_per_promotion", "all"),
    ("Unsafe promoted / evaluated", "unsafe_promotions_per_evaluated", "all"),
    ("Regressions / evaluated", "regressions", "all"),
    ("Missed regressions / regressions", "missed_regressions_per_regression", "all"),
    ("False rejections / safe", "false_rejection_rate", "all"),
    ("Repair success (repair)", "repair_success", "kind=repair"),
    ("Repair success (change request)", "repair_success", "kind=change_request"),
    ("W total", "work_total", "all"),
    ("W mean per transition", "work_mean_per_transition", "all"),
    ("W median per transition", "work_median_per_transition", "all"),
)
OUTCOMES = (
    ("PROMOTE / evaluated", "promote_rate"),
    ("REJECT / evaluated", "reject_rate"),
    ("RETRY / evaluated", "retry_rate"),
    ("ESCALATE / evaluated", "escalate_rate"),
    ("UNKNOWN / required checks", "unknown_rate"),
    ("UNSUPPORTED / required checks", "unsupported_rate"),
)
WORK = (
    ("gate items", "work_gate"),
    ("invariant items from impact", "work_invariant_impact"),
    ("invariant items from the condition", "work_invariant_condition"),
    ("U_t items (not PROTECTED in parent)", "work_invariant_not_protected"),
    ("applicable baseline items", "work_baseline_applicable"),
    ("not-applicable baseline items (outside W)", "work_baseline_not_applicable"),
    ("W total", "work_total"),
)


def _condition_table(
    ix: _Index, conds: Sequence[str], rows: Sequence[tuple[str, str, str]], scope: str
) -> list[str]:
    return _table(
        ["Metric", *[NAMES[c] for c in conds]],
        (
            [label, *[cell(ix.get(name, c, scope, stratum)) for c in conds]]
            for label, name, stratum in rows
        ),
    )


def render_markdown(report: Mapping[str, Any]) -> str:
    ix = _Index(report)
    conds = list(report["conditions"])
    lists = report["lists"]
    prefix = lists["prefix_sizes"]
    saving = cell(ix.get("work_saving_c_vs_b", "C", "common_prefix_B_C"))
    lines: list[str] = [
        "# P8 dev pilot report",
        "",
        *[f"> {line}" for line in report.get("preface") or []],
        *([""] if report.get("preface") else []),
        "Generated by `python -m experiments.report` from the stored trial records;",
        "do not edit by hand.",
        "Descriptive only (C-214): counts, proportions with numerator and denominator, Wilson 95%",
        "intervals. No hypothesis test. These are dev-split numbers of a draft protocol,",
        "not findings.",
        "",
        f"- Experiment: `{report['experiment_name']}` version {report['experiment_version']}, "
        f"id `{report['experiment_id']}`",
        f"- Extractor: `{report['extractor_version']}`",
        f"- Trials: {report['trial_count']} (included {report['included_count']}, "
        f"excluded {report['excluded_count']})",
        f"- Common prefix of all conditions: {prefix['common_prefix_all']} transitions; "
        f"of B and C: {prefix['common_prefix_B_C']}",
        "",
        "## 1. Headline metrics per condition (all evaluated transitions)",
        "",
        *_condition_table(ix, conds, HEADLINE, "all"),
        "",
        "TRUNCATED transitions per condition:",
        "",
        *_table(
            ["Condition", "TRUNCATED / all transitions"],
            ([NAMES[c], cell(ix.get("truncated_transitions", c))] for c in conds),
        ),
        "",
        f"Save(C vs B) on the common prefix of B and C: {saving}",
        "",
        "## 2. The same on the common prefix of all conditions",
        "",
        *_condition_table(
            ix, conds, [r for r in HEADLINE if r[1] != "repair_success"], "common_prefix_all"
        ),
        "",
        "## 3. Per family",
        "",
    ]
    for label, name, _ in HEADLINE[:5]:
        lines += [f"### {label}", ""]
        lines += _table(
            ["Family", *[NAMES[c] for c in conds]],
            (
                [s.removeprefix("family="), *[cell(ix.get(name, c, "all", s)) for c in conds]]
                for s in ix.strata("family=")
            ),
        )
        lines.append("")
    lines += ["## 4. Per tier", ""]
    for label, name, _ in HEADLINE[:5]:
        lines += [f"### {label}", ""]
        lines += _table(
            ["Tier", *[NAMES[c] for c in conds]],
            (
                [s.removeprefix("tier="), *[cell(ix.get(name, c, "all", s)) for c in conds]]
                for s in ix.strata("tier=")
            ),
        )
        lines.append("")
    lines += ["## 5. Outcome rates (Doc 13 §28)", ""]
    lines += _table(
        ["Rate", *[NAMES[c] for c in conds]],
        ([lab, *[cell(ix.get(n, c)) for c in conds]] for lab, n in OUTCOMES),
    )
    lines += [
        "",
        "Non-PASS required checks (fresh results), by condition, kind, verifier, result and "
        "reason:",
        "",
    ]
    non_pass = lists.get("non_pass_checks", [])
    if non_pass:
        lines += _table(
            ["Condition", "Kind", "Verifier", "Result", "Reason", "Count"],
            (
                [
                    NAMES[r["condition"]],
                    r["kind"],
                    r["verifier_id"],
                    r["result"],
                    r["reason"] or "—",
                    str(r["count"]),
                ]
                for r in non_pass
            ),
        )
    else:
        lines.append("none")
    lines += ["", "## 6. Work by kind (oracle excluded)", ""]
    lines += _table(
        ["Kind", *[NAMES[c] for c in conds]],
        ([lab, *[cell(ix.get(n, c)) for c in conds]] for lab, n in WORK),
    )
    lines += ["", "## 7. DAIL–oracle agreement under B (C-155): S0 and every evaluated step", ""]
    for invariant, cells in sorted(report["confusion"].items()):
        lines += [f"### {invariant}", ""]
        lines += _table(
            ["DAIL", "oracle truth", "count"],
            ([c["dail"], c["oracle_truth"], str(c["count"])] for c in cells),
        )
        lines.append("")
    disagreements = lists.get("disagreements", [])
    by_inv = Counter(d["invariant_id"] for d in disagreements)
    lines += [
        f"Disagreements: {len(disagreements)}"
        + (
            ""
            if not by_inv
            else " (" + ", ".join(f"{k}: {v}" for k, v in sorted(by_inv.items())) + ")"
        ),
        "",
    ]
    if disagreements:
        lines += _table(
            ["Scenario", "Step", "Invariant", "DAIL", "Oracle truth"],
            (
                [d["scenario_id"], str(d["step"]), d["invariant_id"], d["dail"], d["oracle_truth"]]
                for d in disagreements
            ),
        )
        lines.append("")
    lines += ["## 8. Impact against the oracle's affected set (C and C′)", ""]
    impact_conds = [c for c in conds if c in ("C", "C_PRIME")]
    strata = ["all", *ix.strata("family=")]
    for label, name in (
        ("Precision", "impact_precision"),
        ("Recall", "impact_recall"),
        ("Truth-change coverage", "truth_change_coverage"),
    ):
        lines += [f"### {label}", ""]
        lines += _table(
            ["Stratum", *[NAMES[c] for c in impact_conds]],
            ([s, *[cell(ix.get(name, c, "all", s)) for c in impact_conds]] for s in strata),
        )
        lines.append("")
    outside = lists.get("truth_changes_outside_v", [])
    lines += [f"Truth changes outside the verified set: {len(outside)}", ""]
    if outside:
        lines += _table(
            ["Condition", "Scenario", "Step", "Invariant"],
            (
                [NAMES[o["condition"]], o["scenario_id"], str(o["step"]), o["invariant_id"]]
                for o in outside
            ),
        )
        lines.append("")
    lines += ["## 9. Identity (H3: C and C′)", ""]
    lines += _table(
        ["Metric", *[NAMES[c] for c in impact_conds]],
        (
            [lab, *[cell(ix.get(n, c)) for c in impact_conds]]
            for lab, n in (
                ("Identity errors / true pairs", "identity_error_rate"),
                ("UNCERTAIN / true pairs", "identity_uncertain_share"),
                ("Evidence-transfer errors", "evidence_transfer_errors"),
                ("Excluded pairs", "identity_excluded_pairs"),
            )
        ),
    )
    errors = lists.get("identity_errors", [])
    lines += ["", f"Identity errors: {len(errors)}", ""]
    if errors:
        lines += _table(
            ["Condition", "Scenario", "Step", "Operator", "Effect", "Old", "New", "DAIL pairs"],
            (
                [
                    NAMES[e["condition"]],
                    e["scenario_id"],
                    str(e["step"]),
                    e["operator"],
                    e["effect"],
                    str(e["old"]),
                    str(e["new"]),
                    "; ".join(f"{p[0]} -> {p[1]} {p[2]}" for p in e["dail_pairs"]) or "none",
                ]
                for e in errors
            ),
        )
        lines.append("")
    excluded = Counter((e["condition"], e["operator"]) for e in lists.get("identity_excluded", []))
    lines += [f"Excluded identity pairs by operator: {sum(excluded.values())}", ""]
    if excluded:
        lines += _table(
            ["Condition", "Operator", "Pairs"],
            ([NAMES[c], op, str(n)] for (c, op), n in sorted(excluded.items())),
        )
        lines.append("")
    diff = lists.get("work_difference_f5", {})
    lines += ["Work difference C′ − C on F5 by moved resource type:", ""]
    if diff:
        lines += _table(
            ["Moved type", "Transitions", "W under C", "W under C′", "C′ − C"],
            (
                [
                    k,
                    str(v["transitions"]),
                    str(v["work_c"]),
                    str(v["work_c_prime"]),
                    str(v["difference"]),
                ]
                for k, v in diff.items()
            ),
        )
    else:
        lines.append("none")
    lines += ["", "## 10. Unsafe promotions under C (Doc 13 §37, §49)", ""]
    unsafe = lists.get("unsafe_promotions_c", [])
    if not unsafe:
        lines.append("none")
    for u in unsafe:
        work = ", ".join(w["target_id"] + "=" + w["result"] for w in u["work"])
        lines += [
            f"- `{u['scenario_id']}` step {u['step']}: failing {', '.join(u['failing'])}; "
            f"impact {{{', '.join(u['impact'])}}}; work {work}",
        ]
    lines += ["", "## 11. Clusters (C-214)", ""]
    lines += _table(
        [
            "Condition",
            "Tier",
            "Clusters",
            "Evaluated",
            "Promoted",
            "Unsafe promoted",
            "Safe",
            "Safe not promoted",
        ],
        _cluster_rows(lists.get("clusters", []), conds),
    )
    lines += ["", "## 12. Failed and excluded trials", ""]
    if not report["failures"]:
        lines.append("none: every trial is COMPLETED and included")
    for f in report["failures"]:
        lines.append(f"- `{f['trial_id']}`: {f['status']}")
    repro = report.get("reproducibility_summary") or {}
    lines += ["", "## 13. Reproducibility (Doc 13 §30)", ""]
    if not repro:
        lines.append("not recorded in this report")
    for key, value in sorted(repro.items()):
        lines.append(f"- {key}: {value}")
    return "\n".join(lines) + "\n"


def _cluster_rows(rows: Sequence[Mapping[str, Any]], conds: Sequence[str]) -> list[list[str]]:
    totals: dict[tuple[str, str], Counter[str]] = {}
    for r in rows:
        key = (r["condition"], r["tier"])
        c = totals.setdefault(key, Counter())
        c["clusters"] += 1
        for k in ("evaluated", "promoted", "unsafe_promoted", "safe", "safe_not_promoted"):
            c[k] += r[k]
    return [
        [
            NAMES[c],
            tier,
            *(
                str(v[k])
                for k in (
                    "clusters",
                    "evaluated",
                    "promoted",
                    "unsafe_promoted",
                    "safe",
                    "safe_not_promoted",
                )
            ),
        ]
        for (c, tier), v in sorted(
            totals.items(),
            key=lambda kv: (conds.index(kv[0][0]) if kv[0][0] in conds else 9, kv[0][1]),
        )
    ]
