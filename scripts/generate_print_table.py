"""Generate ``core/terraform_model/print_table.py``: Go's ``unicode.IsPrint`` for Unicode 15.0.0.

Usage (not run in CI; the output is committed):

    python scripts/generate_print_table.py PATH/TO/UnicodeData.txt [--check]

Terraform writes the string key of a ``for_each`` instance as ``["..."]`` and escapes every
character that Go's ``unicode.IsPrint`` rejects as ``\\uXXXX`` or ``\\UXXXXXXXX`` (``internal/addrs/
instance_key.go``, ``toHCLQuotedString``, tag v1.15.8). ``IsPrint`` is true for the letters, marks,
numbers, punctuation and symbols (general categories L, M, N, P, S) and the ASCII space.

Which Unicode version Terraform 1.15.8 uses was measured, not assumed: ``terraform plan`` of
``terraform_data`` resources (builtin provider, scratch directory outside the repository, no
credentials) prints U+00E9 and U+1F600 as they are and escapes U+1C89 (assigned in Unicode 16.0)
and U+2EBF0 (assigned in Unicode 15.1), so its Go tables are Unicode 15.0.0.

The source is ``https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt``. Standard library only
(no ``unicodedata``, so the result does not depend on the interpreter). ``--check`` compares the
generated text with the committed module.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

EXPECTED_SHA256 = "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73"
SOURCE_URL = "https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt"
OUTPUT = Path(__file__).resolve().parent.parent / "core" / "terraform_model" / "print_table.py"
PRINTABLE_CATEGORIES = ("L", "M", "N", "P", "S")


def printable_points(text: str) -> set[int]:
    """The code points of general category L, M, N, P or S, plus the ASCII space."""
    points = {0x20}
    first: int | None = None
    for line in text.splitlines():
        if not line:
            continue
        fields = line.split(";")
        code, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = code
            continue
        low = code
        if name.endswith(", Last>"):
            if first is None:
                raise SystemExit("a Last entry without its First entry")
            low, first = first, None
        if category.startswith(PRINTABLE_CATEGORIES):
            points.update(range(low, code + 1))
    return points


def to_ranges(points: set[int]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for point in sorted(points):
        if ranges and ranges[-1][1] + 1 == point:
            ranges[-1] = (ranges[-1][0], point)
        else:
            ranges.append((point, point))
    return ranges


def render(source: bytes) -> str:
    digest = hashlib.sha256(source).hexdigest()
    ranges = to_ranges(printable_points(source.decode("utf-8")))
    rows = "".join(f"    (0x{low:X}, 0x{high:X}),\n" for low, high in ranges)
    return (
        '"""Go ``unicode.IsPrint`` for Unicode 15.0.0, as Terraform 1.15.8 uses it.\n\n'
        "GENERATED; do not edit by hand.\n\n"
        "Generated by scripts/generate_print_table.py from\n"
        f"    file     {SOURCE_URL}\n"
        f"    SHA-256  {digest}\n"
        "    use      internal/addrs/instance_key.go, toHCLQuotedString (terraform v1.15.8)\n\n"
        "PRINTABLE holds inclusive (low, high) code point ranges, sorted: the general categories\n"
        "L, M, N, P and S, and the ASCII space.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        f'SOURCE_SHA256 = "{digest}"\n'
        'SOURCE_UNICODE_VERSION = "15.0.0"\n\n'
        f"PRINTABLE: tuple[tuple[int, int], ...] = (\n{rows})\n"
    )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path, help="UnicodeData.txt of Unicode 15.0.0")
    parser.add_argument("--check", action="store_true", help="compare with the committed module")
    args = parser.parse_args(argv)
    source = args.source.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if digest != EXPECTED_SHA256:
        print(f"unexpected SHA-256 {digest}; expected {EXPECTED_SHA256}", file=sys.stderr)
        return 2
    text = render(source)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8")
        if current != text:
            print("print_table.py differs from the generated text", file=sys.stderr)
            return 1
        print("print_table.py is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
