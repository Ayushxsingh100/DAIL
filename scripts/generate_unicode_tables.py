"""Generate ``core/terraform_model/hcl/unicode_tables.py`` from HCL's own identifier tables (C-101).

Usage (not run in CI; the output is committed):

    python scripts/generate_unicode_tables.py PATH/TO/hclsyntax/unicode_derived.rl [--check]

Terraform 1.15.8 is built with ``github.com/hashicorp/hcl/v2 v2.24.0``
(``go.mod`` of hashicorp/terraform at tag v1.15.8, line 36). That version's
``hclsyntax/unicode_derived.rl`` was "autogenerated with unicode2ragel.rb from
http://www.unicode.org/Public/9.0.0/ucd/DerivedCoreProperties.txt" and defines ``ID_Start`` and
``ID_Continue`` as alternatives of UTF-8 byte ranges. This script decodes those alternatives into
code point ranges. Some alternatives have loose trailing byte ranges (``0x00..0xFF``); only the
bytes that complete a well-formed UTF-8 sequence are kept, so the result is the set of code points
the machine accepts as characters.

Standard library only. ``--check`` compares the generated text with the committed module.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

EXPECTED_SHA256 = "c519389245d3f319479d8e262994d98cb055db657a486b83d7d99b3656c1e561"
SOURCE_REPOSITORY = "github.com/hashicorp/hcl"
SOURCE_TAG = "v2.24.0"
SOURCE_PATH = "hclsyntax/unicode_derived.rl"
SOURCE_UNICODE = "9.0.0 (DerivedCoreProperties.txt, as stated in the file header)"
SCANNER_LINE = "hclsyntax/scan_tokens.rl line 46: Ident = (ID_Start | '_') (ID_Continue | '-')*;"
OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "core"
    / "terraform_model"
    / "hcl"
    / "unicode_tables.py"
)


def parse_byte_range(token: str) -> tuple[int, int]:
    if ".." in token:
        low, high = token.split("..")
        return int(low, 16), int(high, 16)
    value = int(token, 16)
    return value, value


def machine_lines(text: str, name: str) -> list[list[tuple[int, int]]]:
    """The alternatives of ``name = ... ;`` as lists of byte ranges."""
    lines = text.splitlines()
    start = next(i for i, line in enumerate(lines) if line.strip() == f"{name} =")
    alternatives: list[list[tuple[int, int]]] = []
    for line in lines[start + 1 :]:
        stripped = line.strip()
        if stripped == ";":
            break
        code = stripped.split("#", 1)[0].strip()
        if code.startswith("|"):
            code = code[1:].strip()
        if not code:
            continue
        alternatives.append([parse_byte_range(token) for token in code.split()])
    return alternatives


def code_points(alternative: list[tuple[int, int]]) -> set[int]:
    """The code points of the well-formed UTF-8 sequences inside the byte ranges."""
    found: set[int] = set()
    first_low, first_high = alternative[0]
    for lead in range(first_low, first_high + 1):
        if lead < 0x80:
            if len(alternative) == 1:
                found.add(lead)
            continue
        length = (
            2
            if 0xC2 <= lead <= 0xDF
            else 3 if 0xE0 <= lead <= 0xEF else 4 if 0xF0 <= lead <= 0xF4 else 0
        )
        if length != len(alternative):
            continue
        sequences = [bytes([lead])]
        for low, high in alternative[1:]:
            low, high = max(low, 0x80), min(high, 0xBF)
            sequences = [s + bytes([b]) for s in sequences for b in range(low, high + 1)]
        for sequence in sequences:
            try:
                found.add(ord(sequence.decode("utf-8")))
            except UnicodeDecodeError:
                continue  # overlong, surrogate or beyond U+10FFFF: not a character
    return found


def to_ranges(points: set[int]) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    for point in sorted(points):
        if ranges and ranges[-1][1] + 1 == point:
            ranges[-1] = (ranges[-1][0], point)
        else:
            ranges.append((point, point))
    return ranges


def render(source: bytes) -> str:
    text = source.decode("utf-8")
    start: set[int] = set()
    for alternative in machine_lines(text, "ID_Start"):
        start |= code_points(alternative)
    cont: set[int] = set()
    for alternative in machine_lines(text, "ID_Continue"):
        cont |= code_points(alternative)
    if not start <= cont:
        raise SystemExit("ID_Start is not inside ID_Continue: the table format would be wrong")

    def block(name: str, points: set[int]) -> str:
        rows = "".join(f"    (0x{low:X}, 0x{high:X}),\n" for low, high in to_ranges(points))
        return f"{name}: tuple[tuple[int, int], ...] = (\n{rows})\n"

    return (
        '"""Identifier tables of Terraform 1.15.8 (C-101). GENERATED; do not edit by hand.\n\n'
        "Generated by scripts/generate_unicode_tables.py from\n"
        f"    repository   {SOURCE_REPOSITORY}\n"
        f"    tag          {SOURCE_TAG} (hcl version in go.mod of terraform v1.15.8, line 36)\n"
        f"    file         {SOURCE_PATH}\n"
        f"    SHA-256      {hashlib.sha256(source).hexdigest()}\n"
        f"    Unicode      {SOURCE_UNICODE}\n"
        f"    scanner rule {SCANNER_LINE}\n\n"
        "ID_START and ID_CONTINUE are inclusive (low, high) code point ranges, sorted.\n"
        "ID_CONTINUE contains ID_START. The lexer adds '_' as a start character and '-' as a\n"
        "continue character itself, as the scanner rule does.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        f'SOURCE_SHA256 = "{hashlib.sha256(source).hexdigest()}"\n'
        f'SOURCE_UNICODE_VERSION = "9.0.0"\n\n'
        + block("ID_START", start)
        + "\n"
        + block("ID_CONTINUE", cont)
    )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path, help="hclsyntax/unicode_derived.rl at hcl v2.24.0")
    parser.add_argument("--check", action="store_true", help="compare with the committed module")
    args = parser.parse_args(argv)
    data = args.source.read_bytes().replace(b"\r\n", b"\n")
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        print(
            f"unexpected source file: SHA-256 {digest}, expected {EXPECTED_SHA256}", file=sys.stderr
        )
        return 2
    text = render(data)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n")
        if current != text:
            print("unicode_tables.py differs from the generated text", file=sys.stderr)
            return 1
        print("unicode_tables.py matches the generated text")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
